/**
 * Writes the room's model files (assets/models/*.glb) and its recorded sounds (the ones listed in src/room/soundfiles.ts)
 * into src/embedded/ as plain modules, base64 by file name, so the frontend imports them like any other code. They are
 * kept in git: Lumiverse builds an extension installed from GitHub with a plain `bun build src/frontend.ts`, without
 * this repository's scripts, and the room needs nothing fetched at run time but the music. scripts/build.ts runs this
 * first, and tests/embedded.test.ts fails when they no longer match the assets.
 *
 *   bun run embed
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { SOUND_FILES } from "../src/room/soundfiles.js";

/** The model files, by name, in a fixed order. */
export const modelFiles = (): string[] => readdirSync("assets/models").filter((f) => f.endsWith(".glb")).sort();

/** A module that exports `name`: each file in `dir`, base64, by file name. */
export function embedded(name: string, dir: string, files: readonly string[]): string {
  const rows = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(`${dir}/${f}`).toString("base64"))},`);
  return `// Generated by scripts/embed.ts from ${dir}. Do not edit: run \`bun run embed\`.\nexport const ${name} = {\n${rows.join("\n")}\n};\n`;
}

/** The pictures painted for the cards, by name, in a fixed order. */
export const cardFiles = (): string[] => readdirSync("assets/cards").filter((f) => f.endsWith(".webp")).sort();

export const EMBEDDED = {
  "src/embedded/pictures.js": () => embedded("CARD_PICTURES", "assets/cards", cardFiles()),
  "src/embedded/models.js": () => embedded("MODELS", "assets/models", modelFiles()),
  "src/embedded/sounds.js": () => embedded("SOUNDS", "assets/sounds", SOUND_FILES),
} as const;

if (import.meta.main) {
  for (const [path, make] of Object.entries(EMBEDDED)) {
    const text = make();
    let old = "";
    try {
      old = readFileSync(path, "utf8");
    } catch {}
    if (old !== text) writeFileSync(path, text);
    console.log(`${path}  ${(text.length / 1024).toFixed(0)} KB${old === text ? "" : " (written)"}`);
  }
}
