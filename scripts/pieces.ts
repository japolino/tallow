/**
 * Writes the list of music the room may play (src/embedded/pieces.js) from the composer's own listing of his library:
 * every piece by Kevin MacLeod on incompetech.com, all under Creative Commons: By Attribution 4.0. Only what a piece
 * is called and how it is tagged is kept (its file, length, tempo, genre, feel, instruments, collection); the music
 * itself is streamed from his site while it plays and is never part of this repository.
 *
 *   bun scripts/pieces.ts              fetch the listing and write the module
 *   bun scripts/pieces.ts listing.json from a copy already fetched
 *
 * Run by hand when the library should be read again. The module is kept in git, like the other embedded ones: an
 * install from GitHub is built with a plain `bun build`, and a page cannot fetch the listing itself.
 */
import { readFileSync, writeFileSync } from "node:fs";

const LISTING = "https://incompetech.com/music/royalty-free/pieces.json";
const OUT = "src/embedded/pieces.js";

/** The listing's own numbers for its genres and collections, as its page names them. */
const GENRES: Record<string, string> = {
  2: "African", 3: "Blues", 4: "Classical", 5: "Contemporary", 6: "Disco", 7: "Electronica", 8: "Funk", 9: "Holiday", 10: "Horror", 11: "Jazz",
  12: "Latin", 13: "Modern", 14: "Musical", 15: "Polka", 16: "Pop", 18: "Reggae", 19: "Rock", 20: "Silent Film Score", 21: "Ska", 22: "Soundtrack",
  23: "Stings", 24: "Unclassifiable", 25: "World", 26: "Urban",
};
const COLLECTIONS: Record<string, string> = {
  1: "Hard Electronic", 2: "Medium Electronic", 3: "Video Classica", 4: "Disco and Lounge", 5: "Rock Classic", 6: "Rock Medium", 7: "Rock Harder",
  8: "Funk and Blues", 9: "African", 10: "Middle East Inspired", 11: "Reggae and Ska", 12: "Polka", 13: "Celtic and Folk", 14: "Native American",
  15: "Latin Sounds", 16: "Jazz", 17: "Far East Inspired", 18: "Silent Film, Bright", 19: "Silent Film, Dark", 20: "Action", 21: "Comedic",
  22: "Darkness and Unease", 23: "Gloom and Sadness", 24: "Horror Soundscapes", 25: "Horror Themes", 27: "Mystery", 28: "Noire", 30: "Aspiring",
  31: "Tension", 32: "Wonder", 33: "Bright Piano", 37: "Light", 38: "Elegant Piano", 39: "Heartfelt Melodies", 40: "Thoughtful", 41: "Serenity",
  42: "Touching Moments", 43: "Christmas", 44: "Danse Macabre", 45: "Dark World", 46: "Famous Classics", 47: "Mad Pianist", 48: "Oddities",
  49: "Wonders of Other Worlds", 52: "Western European", 54: "Polynesian", 56: "Brazilian",
};

/** A piece is kept when it is long enough to play under a scene and not so long that one pick lasts the evening. */
const SHORTEST = 80, LONGEST = 720;

interface Listed {
  title?: string; filename?: string; length?: string; instruments?: string | null; genre?: string | null; bpm?: string | null; feel?: string | null; collection?: string | null;
}

const seconds = (s: string): number => s.split(":").reduce((n, p) => n * 60 + Math.floor(Number(p) || 0), 0);
const tidy = (s: string | null | undefined): string => (s ?? "").split(",").map((t) => t.replace(/\s+/g, " ").trim()).filter(Boolean).join(", ");

/** The module's text for a listing: one row a piece, [title, file, seconds, bpm, genre, feels, instruments, collection]. */
export function piecesModule(listing: Listed[]): string {
  const seen = new Set<string>();
  const rows: string[] = [];
  for (const p of listing) {
    const title = (p.title ?? "").replace(/\s+/g, " ").trim(), file = p.filename ?? "";
    const genre = GENRES[String(p.genre ?? "")] ?? "";
    const secs = seconds(p.length ?? "");
    if (!title || !/\.mp3$/i.test(file) || !genre || genre === "Stings" || secs < SHORTEST || secs > LONGEST) continue;
    const feels = tidy(p.feel);
    if (!feels || seen.has(title.toLowerCase())) continue;
    seen.add(title.toLowerCase());
    // The file's name is kept only where it is not simply the title.
    rows.push(JSON.stringify([title, file === `${title}.mp3` ? "" : file, secs, Math.round(Number(p.bpm) || 0), genre, feels, tidy(p.instruments), COLLECTIONS[String(p.collection ?? "")] ?? ""]));
  }
  rows.sort();
  return `// Generated by scripts/pieces.ts from ${LISTING}. Do not edit: run \`bun scripts/pieces.ts\`.\n// Each row: [title, file ("" when it is the title + ".mp3"), seconds, beats a minute, genre, feels, instruments, collection].\nexport const PIECES = [\n${rows.map((r) => `  ${r},`).join("\n")}\n];\n`;
}

if (import.meta.main) {
  const from = process.argv[2];
  const text = from ? readFileSync(from, "utf8") : await (await fetch(LISTING, { headers: { "user-agent": "Mozilla/5.0" } })).text();
  const out = piecesModule(JSON.parse(text) as Listed[]);
  writeFileSync(OUT, out);
  console.log(`${OUT}  ${out.split("\n").length - 4} pieces, ${(out.length / 1024).toFixed(0)} KB`);
}
